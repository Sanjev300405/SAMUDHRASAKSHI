"""Generate contracts.ts from contracts.py so the two can never hand-drift.

Usage:
    python contracts/generate_ts.py                 # regenerate both copies
    python contracts/generate_ts.py --check          # exit 1 if outputs are stale

Writes identical content to two places (single generator, two consumers):
  - contracts/contracts.ts                        (repo-layout canonical copy)
  - frontend/src/lib/contracts.generated.ts        (what the frontend imports)

Do not hand-edit either output. Edit contracts.py and rerun this script.
"""

from __future__ import annotations

import argparse
import datetime as dt
import sys
import types
import typing
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import contracts as C  # noqa: E402
from pydantic import BaseModel  # noqa: E402

HEADER = """// AUTO-GENERATED by contracts/generate_ts.py from contracts/contracts.py.
// Do not hand-edit. Run `python contracts/generate_ts.py` after changing the
// Pydantic models — this file and contracts.py can never drift apart because
// one is mechanically derived from the other.
"""


def py_type_to_ts(tp: object) -> str:
    if tp is type(None):
        return "null"
    if tp is str:
        return "string"
    if tp in (int, float):
        return "number"
    if tp is bool:
        return "boolean"
    if tp is dt.datetime:
        return "string"
    origin = typing.get_origin(tp)
    args = typing.get_args(tp)

    if origin is typing.Literal:
        return " | ".join(f'"{a}"' for a in args)

    if origin in (typing.Union, types.UnionType):
        return " | ".join(py_type_to_ts(a) for a in args)

    if origin is list:
        inner = py_type_to_ts(args[0]) if args else "unknown"
        needs_parens = "|" in inner
        return f"({inner})[]" if needs_parens else f"{inner}[]"

    if origin is tuple:
        if len(args) == 2 and args[1] is Ellipsis:
            return f"{py_type_to_ts(args[0])}[]"
        return "[" + ", ".join(py_type_to_ts(a) for a in args) + "]"

    if isinstance(tp, type) and issubclass(tp, BaseModel):
        return tp.__name__

    return "unknown"


def emit_interface(model: type[BaseModel]) -> str:
    lines = [f"export interface {model.__name__} {{"]
    for name, field in model.model_fields.items():
        ts_type = py_type_to_ts(field.annotation)
        lines.append(f"  {name}: {ts_type};")
    lines.append("}")
    return "\n".join(lines)


def collect_models() -> list[type[BaseModel]]:
    seen: dict[str, type[BaseModel]] = {}
    for name in dir(C):
        obj = getattr(C, name)
        if isinstance(obj, type) and issubclass(obj, BaseModel) and obj is not BaseModel:
            seen[obj.__name__] = obj
    # stable, readable order: spine first, composites last
    order = [
        "Provenance", "GeoJSONPolygon", "SlickObservation",
        "OriginEstimate", "AISFix", "AISQuality", "AISTrack",
        "BestRelease", "Evidence", "CandidateScore",
        "Weights", "DriftCfg", "ConfigSnapshot", "Assets", "CaseBundle",
    ]
    ordered = [seen.pop(n) for n in order if n in seen]
    ordered.extend(seen.values())
    return ordered


def build_ts_source() -> str:
    parts = [HEADER]
    parts.append('export type Src = "real" | "provided" | "synthetic";')
    parts.append("export type BBox = [number, number, number, number];\n")
    for model in collect_models():
        parts.append(emit_interface(model))
        parts.append("")
    return "\n".join(parts).rstrip() + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()

    src = build_ts_source()
    repo_root = Path(__file__).resolve().parent.parent
    targets = [
        repo_root / "contracts" / "contracts.ts",
        repo_root / "frontend" / "src" / "lib" / "contracts.generated.ts",
    ]

    if args.check:
        stale = [t for t in targets if not t.exists() or t.read_text(encoding="utf-8") != src]
        if stale:
            print("contracts.ts is stale relative to contracts.py:")
            for t in stale:
                print(f"  {t}")
            print("Run: python contracts/generate_ts.py")
            return 1
        print("contracts.ts is in sync with contracts.py.")
        return 0

    for t in targets:
        t.parent.mkdir(parents=True, exist_ok=True)
        t.write_text(src, encoding="utf-8")
        print(f"wrote {t}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
